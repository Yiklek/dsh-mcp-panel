/**
 * Produce what ships on the `pkg` branch.
 *
 * Why the branch exists: installing from a git ref (`github:owner/repo#pkg`) makes
 * the package manager treat the checkout as SOURCE — it runs `prepare` and installs
 * devDependencies, so every consumer would need esbuild and a toolchain. The `pkg`
 * branch is therefore a BUILT artifact: `lib/` is committed and the manifest drops
 * everything that only makes sense in the source repo.
 *
 * Two things are easy to get wrong here, and both were:
 *
 *   1. `files` must list what ships. Without it, packing falls back to .gitignore,
 *      which ignores `lib/` — the artifact then has no build output.
 *   2. .gitignore itself must stop ignoring `lib/`. Even WITH `files`, a
 *      .gitignore rule wins for anything the manifest does not name — and npm
 *      always includes `main` — so the tarball carried `lib/host.mjs` alone and no
 *      `lib/client.js`. Installing `github:…#pkg` produced a plugin with no browser
 *      half at all, which is invisible until someone opens the panel.
 *
 * Usage: node scripts/pkg-manifest.mjs <source package.json> <output package.json>
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

const [, , sourcePath, outputPath] = process.argv
if (sourcePath === undefined || outputPath === undefined) {
  console.error('usage: node scripts/pkg-manifest.mjs <source> <output>')
  process.exit(2)
}

const manifest = JSON.parse(readFileSync(sourcePath, 'utf8'))

// Build tooling is irrelevant once `lib/` is committed, and `prepare` would try to
// run it. Keeping either is the exact failure this branch avoids.
delete manifest.scripts
delete manifest.devDependencies
delete manifest.packageManager

// Say explicitly what ships; do not inherit the source repo's ignore rules.
manifest.files = ['lib/', 'cordis.patch.yml', 'locale/']

// Consumers never build here; say so in the artifact itself.
manifest.description =
  (manifest.description ?? '') +
  (manifest.description === undefined ? '' : ' — ') +
  'built artifact branch; generated by .github/workflows/ci.yml, do not edit'

writeFileSync(outputPath, JSON.stringify(manifest, null, 2) + '\n')
console.log('wrote ' + outputPath + ' (' + Object.keys(manifest).join(', ') + ')')

// The artifact branch must not ignore its own build output (see the note above).
const ignorePath = join(dirname(outputPath), '.gitignore')
if (existsSync(ignorePath)) {
  const kept = readFileSync(ignorePath, 'utf8')
    .split('\n')
    .filter((line) => line.trim() !== 'lib/')
    .join('\n')
  writeFileSync(ignorePath, kept)
  console.log('removed the lib/ ignore from ' + ignorePath)
}
